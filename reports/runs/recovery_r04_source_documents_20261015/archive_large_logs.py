"""Losslessly archive a pytest parameter-name expansion before staging evidence."""

import gzip
import hashlib
import json
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

root = Path(__file__).resolve().parent
receipt = []
for name in ("unit_first.log", "unit_first.xml"):
    original = root / name
    assert original.resolve().parent == root
    body = original.read_bytes()
    archive = original.with_name(name + ".gz")
    compressed = gzip.compress(body, mtime=0)
    archive.write_bytes(compressed)
    assert gzip.decompress(archive.read_bytes()) == body
    receipt.append(
        {
            "original": name,
            "archive": archive.name,
            "original_bytes": len(body),
            "original_sha256": hashlib.sha256(body).hexdigest(),
            "archive_bytes": len(compressed),
            "archive_sha256": hashlib.sha256(compressed).hexdigest(),
        }
    )
    original.unlink()
(root / "large_log_archive.json").write_text(
    json.dumps(
        {
            "archived_at": datetime.now(ZoneInfo("Asia/Shanghai")).isoformat(timespec="seconds"),
            "files": receipt,
            "reason": "pytest autogenerated ID hit Windows env length; raw bytes preserved",
        },
        indent=2,
    )
    + "\n",
    encoding="utf-8",
)
print(json.dumps(receipt))
