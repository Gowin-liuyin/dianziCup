"""Seal the completed review, all receipts and raw artifacts; excludes only its own manifest."""

import datetime
import hashlib
import json
from pathlib import Path
import subprocess

RUN = Path(__file__).resolve().parent
REPORT = Path('D:/dianzi/reports/reviews/recovery/G-C-R10-pg-evidence-graph-review-1.md')
ROOT = Path('D:/wt/r10-graph-review1')
started = datetime.datetime.now().astimezone().isoformat()
paths = sorted([p for p in RUN.iterdir() if p.is_file() and p.name != 'reviewer_artifact_manifest.json'] + [REPORT])
entries = []
for path in paths:
    content = path.read_bytes()
    entries.append({'path': str(path), 'raw_bytes': len(content), 'raw_sha256': hashlib.sha256(content).hexdigest()})
assert subprocess.check_output(['git', 'status', '--short'], cwd=ROOT, text=True) == ''
manifest = {
    'code_sha': 'b0b7a5b856cc38862f64c01565309564d67c34c0',
    'material_sha': '16803ce6be9ad6adb6d89f46c594cfa420190c24',
    'verdict': 'needs_changes', 'files': entries,
    'command': ['D:/wt/r10-graph-review1/backend/.venv/Scripts/python.exe', str(Path(__file__))],
    'cwd': str(ROOT / 'backend'), 'started_at': started,
    'finished_at': datetime.datetime.now().astimezone().isoformat(), 'exit_code': 0,
    'excluded': ['reviewer_artifact_manifest.json (self-reference)', '__pycache__ directories (generated bytecode)'],
    'review_worktree_clean': True,
}
path = RUN / 'reviewer_artifact_manifest.json'
path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding='utf-8')
print(json.dumps({'files_sealed': len(entries), 'manifest_bytes': path.stat().st_size, 'manifest_sha256': hashlib.sha256(path.read_bytes()).hexdigest(), 'report_bytes': REPORT.stat().st_size, 'report_sha256': hashlib.sha256(REPORT.read_bytes()).hexdigest()}, indent=2))
