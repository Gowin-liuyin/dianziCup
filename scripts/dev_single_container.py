"""Run the main-path smoke inside one throwaway container on in-container loopback.

The host Docker data plane is known to black-hole host-to-container and
container-to-container TCP (progress/OPEN_QUESTIONS.md OQ-1), while
in-container loopback and container outbound access work. This script therefore
builds a one-off image with PostgreSQL 16 + pgvector and uv, starts one
container limited to 2g memory / 2 cpus, mounts the repository read-only,
generates disposable database and analyst credentials inside the container, and
executes scripts/smoke_main_path.py there so every connection stays on
127.0.0.1. The container is removed on every exit path; credentials are never
printed and never leave the container environment.

Example: uv run python scripts/dev_single_container.py --attempt-label attempt1
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from datetime import UTC, datetime
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_EVIDENCE_DIR = REPO_ROOT / "reports" / "runs" / "batch21_single_container_smoke"
DEFAULT_IMAGE_TAG = "dianzi:batch21-smoke"
CACHE_VOLUME = "batch21_smoke_uv_cache"
CONTAINER_MEMORY = "2g"
CONTAINER_CPUS = "2"
RUN_TIMEOUT_SECONDS = 2700

CONTAINER_DOCKERFILE = """FROM python:3.12-bookworm
RUN apt-get update \\
 && apt-get install -y --no-install-recommends ca-certificates curl gnupg \\
 && install -d /usr/share/postgresql-common/pgdg \\
 && curl -fsSL https://www.postgresql.org/media/keys/ACCC4CF8.asc -o /usr/share/postgresql-common/pgdg/apt.postgresql.org.asc \\
 && echo "deb [signed-by=/usr/share/postgresql-common/pgdg/apt.postgresql.org.asc] https://apt.postgresql.org/pub/repos/apt bookworm-pgdg main" > /etc/apt/sources.list.d/pgdg.list \\
 && apt-get update \\
 && apt-get install -y --no-install-recommends postgresql-16 postgresql-16-pgvector \\
 && curl -LsSf https://astral.sh/uv/install.sh | sh \\
 && rm -rf /var/lib/apt/lists/*
ENV PATH=/root/.local/bin:/usr/lib/postgresql/16/bin:$PATH
"""

CONTAINER_RUN_SCRIPT = r"""#!/bin/bash
# Generated by scripts/dev_single_container.py. No xtrace anywhere in this
# script: shell command lines carry generated credentials that must not leak.
set -u
export LANG=C.UTF-8 LC_ALL=C.UTF-8 PYTHONUTF8=1 PYTHONDONTWRITEBYTECODE=1
export PATH=/root/.local/bin:/usr/lib/postgresql/16/bin:$PATH

echo "=== container preflight ==="
echo "uname=$(uname -m) python=$(python3 --version 2>&1) uv=$(uv --version 2>&1)"
echo "pg_version=$(ls /usr/lib/postgresql 2>/dev/null | tr '\n' ' ')"

echo "=== postgresql start ==="
pg_ctlcluster 16 main start
start_rc=$?
echo "pg_ctlcluster_start_rc=$start_rc"
if [ "$start_rc" -ne 0 ]; then
  echo "PG_START_FAILED"
  exit 3
fi
ready=1
for _ in $(seq 1 30); do
  if pg_isready -h 127.0.0.1 -p 5432 -q; then ready=0; break; fi
  sleep 1
done
if [ "$ready" -ne 0 ]; then
  echo "PG_NOT_READY"
  exit 3
fi
echo "pg_isready=ok"

SMOKE_DB_PASSWORD=$(python3 -c "import secrets; print(secrets.token_hex(16))")
ANALYST_PASSWORD=$(python3 -c "import secrets; print(secrets.token_hex(16))")
runuser -u postgres -- psql -v ON_ERROR_STOP=1 \
  -c "CREATE ROLE smoke_writer LOGIN SUPERUSER PASSWORD '$SMOKE_DB_PASSWORD'" > /dev/null
role_rc=$?
if [ "$role_rc" -ne 0 ]; then
  echo "ROLE_CREATE_FAILED"
  exit 3
fi
runuser -u postgres -- createdb -O smoke_writer story_smoke_20261024
db_rc=$?
if [ "$db_rc" -ne 0 ]; then
  echo "DB_CREATE_FAILED"
  exit 3
fi
echo "database_ready=127.0.0.1:5432/story_smoke_20261024 (credentials not printed)"

echo "=== uv sync ==="
cd /repo/backend || exit 4
export UV_PROJECT_ENVIRONMENT=/tmp/venv UV_CACHE_DIR=/tmp/uv-cache UV_LINK_MODE=copy
uv sync --locked --no-dev
sync_rc=$?
echo "uv_sync_rc=$sync_rc"
if [ "$sync_rc" -ne 0 ]; then
  echo "UV_SYNC_FAILED"
  exit 4
fi

export DATABASE_URL="postgresql://smoke_writer:${SMOKE_DB_PASSWORD}@127.0.0.1:5432/story_smoke_20261024"
export "$(printf 'ADMIN_USER_PASSWORD=%s' "$ANALYST_PASSWORD")"

echo "=== preflight db probe ==="
uv run --no-sync python - <<'PYEOF'
import hashlib
import os

import psycopg
from sqlalchemy import create_engine, text
from sqlalchemy.dialects import postgresql
from sqlalchemy.engine import make_url

url = os.environ["DATABASE_URL"]
raw_pw = url.split("//", 1)[1].split("@", 1)[0].split(":", 1)[1]
print("raw_pw_len", len(raw_pw), "raw_pw_sha", hashlib.sha256(raw_pw.encode()).hexdigest()[:16])
try:
    with psycopg.connect(url, connect_timeout=5) as connection:
        with connection.cursor() as cursor:
            cursor.execute("SELECT current_user, current_database()")
            print("raw_probe_ok", cursor.fetchone())
except Exception as failure:
    print("raw_probe_failed", type(failure).__name__, str(failure).replace(url, "[redacted]")[:300])

parsed = make_url(url)
normalized = str(parsed.set(drivername="postgresql+psycopg"))
urlsafe_pw = parsed.password or ""
print(
    "parsed_pw_len",
    len(urlsafe_pw),
    "parsed_pw_sha",
    hashlib.sha256(urlsafe_pw.encode()).hexdigest()[:16],
)
print("parsed_host", parsed.host, "port", parsed.port, "user", parsed.username, "db", parsed.database)

dialect = postgresql.psycopg.dialect()
opts = dialect.create_connect_args(make_url(normalized))[1]
print("dialect_opt_keys", sorted(opts.keys()))
for key in sorted(opts.keys()):
    if key == "password":
        value = opts[key] or ""
        print("dialect_pw_len", len(value), "dialect_pw_sha", hashlib.sha256(value.encode()).hexdigest()[:16])
    else:
        print("dialect_opt", key, repr(opts[key]))
try:
    psycopg.connect(**opts, connect_timeout=5)
    print("dialect_kwargs_probe_ok")
except Exception as failure:
    print("dialect_kwargs_probe_failed", type(failure).__name__, str(failure)[:300])

try:
    engine = create_engine(normalized, hide_parameters=True, connect_args={"connect_timeout": 5})
    with engine.connect() as connection:
        connection.execute(text("SELECT 1"))
    print("sqlalchemy_probe_ok")
except Exception as failure:
    print("sqlalchemy_probe_failed", type(failure).__name__, repr(str(failure))[:400])
PYEOF
echo "=== listener and auth config ==="
ss -ltnp 2>/dev/null | grep 5432 || echo "ss_no_listener"
grep -v '^#' /etc/postgresql/16/main/pg_hba.conf | grep -v '^[[:space:]]*$' || true
tail -15 /var/log/postgresql/postgresql-16-main.log 2>/dev/null || echo "no_pg_log"

echo "=== smoke_main_path ==="
uv run --no-sync python /repo/scripts/smoke_main_path.py --port 8000
smoke_rc=$?
echo "smoke_exit=$smoke_rc"
exit "$smoke_rc"
"""


class DockerCommandError(RuntimeError):
    """A docker CLI invocation failed before or during evidence capture."""


def parse_arguments(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="dev_single_container.py",
        description=(
            "Build and run the single-container main-path smoke; all traffic stays "
            "on in-container 127.0.0.1. Container and uv cache volume are removed "
            "unless --keep-cache is given."
        ),
    )
    parser.add_argument(
        "--attempt-label",
        required=True,
        help="evidence file stem, for example attempt1",
    )
    parser.add_argument(
        "--evidence-dir",
        type=Path,
        default=DEFAULT_EVIDENCE_DIR,
        help="directory receiving preflight/build/run logs (default under reports/runs)",
    )
    parser.add_argument(
        "--image-tag",
        default=DEFAULT_IMAGE_TAG,
        help="docker image tag to build or reuse (default dianzi:batch21-smoke)",
    )
    parser.add_argument(
        "--skip-build",
        action="store_true",
        help="reuse an existing image without rebuilding",
    )
    parser.add_argument(
        "--keep-cache",
        action="store_true",
        help="keep the uv download cache volume for faster follow-up attempts",
    )
    return parser.parse_args(argv)


def run_docker(arguments: list[str], timeout_seconds: int) -> subprocess.CompletedProcess[str]:
    """Run one docker CLI call with output captured; never leaks env secrets."""
    return subprocess.run(
        ["docker", *arguments],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=timeout_seconds,
    )


def record_output(
    path: Path, header: str, completed: subprocess.CompletedProcess[str] | None, exit_code: int
) -> None:
    """Append-then-exit-code pattern: stdout/stderr first, exit code last."""
    with path.open("a", encoding="utf-8") as handle:
        handle.write(f"=== {header} ({datetime.now(UTC).isoformat()}) ===\n")
        if completed is not None:
            if completed.stdout:
                handle.write(completed.stdout)
            if completed.stderr:
                handle.write("--- stderr ---\n")
                handle.write(completed.stderr)
        handle.write(f"exit={exit_code}\n")


def image_exists(image_tag: str) -> bool:
    probe = run_docker(["image", "inspect", image_tag], timeout_seconds=60)
    return probe.returncode == 0


def build_image(image_tag: str, evidence_dir: Path) -> None:
    with tempfile.TemporaryDirectory(prefix="dianzi_batch21_build_") as context_name:
        context_dir = Path(context_name)
        dockerfile = context_dir / "Dockerfile"
        dockerfile.write_text(CONTAINER_DOCKERFILE, encoding="utf-8", newline="\n")
        completed = run_docker(
            ["build", "-t", image_tag, str(context_dir)],
            timeout_seconds=1800,
        )
    record_output(evidence_dir / "image_build.txt", f"docker build {image_tag}", completed, completed.returncode)
    if completed.returncode != 0:
        raise DockerCommandError(f"docker build failed with exit {completed.returncode}")


def run_container(
    image_tag: str, repo_mount: str, container_name: str, evidence_dir: Path, attempt_label: str
) -> int:
    remove_container(container_name)
    with tempfile.TemporaryDirectory(prefix="dianzi_batch21_run_") as runner_name:
        runner_path = Path(runner_name) / "run_container.sh"
        runner_path.write_text(CONTAINER_RUN_SCRIPT, encoding="utf-8", newline="\n")
        docker_arguments = [
            "run",
            "--rm",
            "--name",
            container_name,
            "--memory",
            CONTAINER_MEMORY,
            "--cpus",
            CONTAINER_CPUS,
            "-v",
            f"{repo_mount}:/repo:ro",
            "-v",
            f"{runner_path.as_posix()}:/run_container.sh:ro",
            "-v",
            f"{CACHE_VOLUME}:/tmp/uv-cache",
            image_tag,
            "bash",
            "/run_container.sh",
        ]
        try:
            completed = run_docker(docker_arguments, timeout_seconds=RUN_TIMEOUT_SECONDS)
            exit_code = completed.returncode
        except subprocess.TimeoutExpired as timeout_failure:
            completed = None
            exit_code = 124
            record_output(
                evidence_dir / f"{attempt_label}_run.txt",
                f"docker run {container_name} (timed out; tail of captured output)",
                None,
                exit_code,
            )
            with (evidence_dir / f"{attempt_label}_run.txt").open("a", encoding="utf-8") as handle:
                handle.write(str(timeout_failure)[-4000:])
            return exit_code
    record_output(
        evidence_dir / f"{attempt_label}_run.txt",
        f"docker run {container_name}",
        completed,
        exit_code,
    )
    return exit_code


def remove_container(container_name: str) -> None:
    run_docker(["rm", "-f", container_name], timeout_seconds=120)


def main(argv: list[str] | None = None) -> int:
    arguments = parse_arguments(argv)
    evidence_dir = arguments.evidence_dir
    evidence_dir.mkdir(parents=True, exist_ok=True)

    preflight = run_docker(
        ["info", "--format", "{{.ServerVersion}} {{.OperatingSystem}}"], timeout_seconds=60
    )
    record_output(evidence_dir / "preflight.txt", "docker info", preflight, preflight.returncode)
    if preflight.returncode != 0:
        return 2

    if arguments.skip_build or image_exists(arguments.image_tag):
        with (evidence_dir / "image_build.txt").open("a", encoding="utf-8") as handle:
            handle.write(f"=== image reuse ===\nimage={arguments.image_tag} reused=1\nexit=0\n")
    else:
        try:
            build_image(arguments.image_tag, evidence_dir)
        except DockerCommandError as build_failure:
            print(f"ERROR {build_failure}", file=sys.stderr)
            return 3

    container_name = f"dianzi-batch21-{arguments.attempt_label}"
    run_exit_code = run_container(
        arguments.image_tag,
        REPO_ROOT.as_posix(),
        container_name,
        evidence_dir,
        arguments.attempt_label,
    )
    remove_container(container_name)
    if not arguments.keep_cache:
        run_docker(["volume", "rm", CACHE_VOLUME], timeout_seconds=120)

    summary = {
        "attempt": arguments.attempt_label,
        "image": arguments.image_tag,
        "run_exit_code": run_exit_code,
        "smoke_exit_code_contract": "0 pass, 1 assertion failure, 2 config error, 3 postgres setup, 4 uv sync",
        "completed_at": datetime.now(UTC).isoformat(),
    }
    (evidence_dir / f"{arguments.attempt_label}_summary.json").write_text(
        json.dumps(summary, indent=2) + "\n", encoding="utf-8"
    )
    return 0 if run_exit_code == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
