"""Run isolated-PostgreSQL test groups inside one throwaway container on loopback.

Uses the single-container image built by scripts/dev_single_container.py. Each
group in the JSON plan receives its own disposable database and matching
superuser role named test_dianzi_<run_id> so the scripts/dev.py isolation
contract is satisfied on port 5432 with DIANZI_TEST_ISOLATION=container.
Per-group pytest output is written straight into the mounted evidence directory;
credentials are generated inside the container and never printed.

Example: uv run python scripts/dev_integration_container.py --plan reports/runs/batch21_integration_unlocked/groups.json --evidence-dir reports/runs/batch21_integration_unlocked
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from datetime import UTC, datetime
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_IMAGE_TAG = "dianzi:batch21-smoke"
CACHE_VOLUME = "batch21_smoke_uv_cache"
CONTAINER_MEMORY = "2g"
CONTAINER_CPUS = "2"
GROUP_TIMEOUT_SECONDS = 2700
RUN_TIMEOUT_SECONDS = 14400

CONTAINER_RUNNER = r"""#!/bin/bash
# Generated by scripts/dev_integration_container.py. No xtrace: generated
# credentials appear in shell expansions that must not leak to the log.
set -u
export LANG=C.UTF-8 LC_ALL=C.UTF-8 PYTHONUTF8=1 PYTHONDONTWRITEBYTECODE=1
export PATH=/root/.local/bin:/usr/lib/postgresql/16/bin:$PATH

pg_createcluster 16 parentport --port 25432 --start-conf auto > /dev/null 2>&1
pg_ctlcluster 16 main start || { echo "PG_START_FAILED"; exit 3; }
pg_ctlcluster 16 parentport start || { echo "PG_ALTPORT_START_FAILED"; exit 3; }
for _ in $(seq 1 30); do
  pg_isready -h 127.0.0.1 -p 5432 -q && pg_isready -h 127.0.0.1 -p 25432 -q && break
  sleep 1
done
pg_isready -h 127.0.0.1 -p 5432 -q || { echo "PG_NOT_READY"; exit 3; }
pg_isready -h 127.0.0.1 -p 25432 -q || { echo "PG_ALTPORT_NOT_READY"; exit 3; }
echo "pg_isready=ok"

cd /repo/backend || exit 4
export UV_PROJECT_ENVIRONMENT=/tmp/venv UV_CACHE_DIR=/tmp/uv-cache UV_LINK_MODE=copy
uv sync --locked || { echo "UV_SYNC_FAILED"; exit 4; }
echo "uv_sync_rc=0"

python3 /run_groups.py
runner_rc=$?
echo "groups_runner_rc=$runner_rc"
exit "$runner_rc"
"""

GROUPS_RUNNER_PYTHON = r'''"""Provision disposable databases, then run plan groups or per-file entries."""

import json
import os
import secrets
import subprocess
import sys
from pathlib import Path

GROUP_TIMEOUT_SECONDS = 2700
FILE_TIMEOUT_SECONDS = 900
PLAN = json.loads(Path("/groups.json").read_text(encoding="utf-8"))
BACKEND = Path("/repo/backend")
OUTPUT = Path("/out")
ADMIN = "postgres"
PORTS = (5432, 25432)


def provision(run_id: str, password: str, port: int) -> None:
    user = database = f"test_dianzi_{run_id}"
    base = ["runuser", "-u", ADMIN, "--", "psql", "-p", str(port)]
    role_exists = subprocess.run(
        [*base, "-tAc", f"SELECT 1 FROM pg_roles WHERE rolname = '{user}'"],
        capture_output=True, text=True,
    ).stdout.strip()
    if role_exists == "1":
        subprocess.run(
            [*base, "-v", "ON_ERROR_STOP=1", "-c",
             f"ALTER ROLE {user} LOGIN SUPERUSER PASSWORD '{password}'"],
            check=True, capture_output=True, text=True,
        )
    else:
        subprocess.run(
            [*base, "-v", "ON_ERROR_STOP=1", "-c",
             f"CREATE ROLE {user} LOGIN SUPERUSER PASSWORD '{password}'"],
            check=True, capture_output=True, text=True,
        )
    db_exists = subprocess.run(
        [*base, "-tAc", f"SELECT 1 FROM pg_database WHERE datname = '{database}'"],
        capture_output=True, text=True,
    ).stdout.strip()
    if db_exists != "1":
        subprocess.run(
            ["runuser", "-u", ADMIN, "--", "createdb", "-p", str(port), "-O", user, database],
            check=True, capture_output=True, text=True,
        )
    database_url = (
        f"postgresql://{user}:{password}@127.0.0.1:{port}/{database}"
    )
    migration = subprocess.run(
        ["uv", "run", "--no-sync", "python", "/repo/scripts/migrate.py"],
        cwd=BACKEND,
        env={**os.environ, "DATABASE_URL": database_url, "DATA_MODE": "fixture"},
        capture_output=True, text=True,
    )
    if migration.returncode != 0:
        raise RuntimeError(
            f"migration failed for {database}@{port}: {migration.stderr[-500:]}"
        )


def build_environment(run_id: str, port: int) -> dict[str, str]:
    password = secrets.token_hex(16)
    for cluster_port in PORTS:
        provision(run_id, password, cluster_port)
    environment = os.environ.copy()
    environment.update(
        {
            "DIANZI_TEST_RUN_ID": run_id,
        "TEST_DATABASE_URL": (
            f"postgresql+psycopg://test_dianzi_{run_id}:{password}"
            f"@127.0.0.1:{port}/test_dianzi_{run_id}"
        ),
            "DIANZI_TEST_ISOLATION": "container",
            "COVERAGE_FILE": "/tmp/.coverage",
        }
    )
    return environment


def capture(output_path: Path, header: str, completed, exit_code: int) -> None:
    with output_path.open("w", encoding="utf-8") as handle:
        handle.write(header)
        if completed is not None:
            if completed.stdout:
                handle.write(completed.stdout)
            if completed.stderr:
                handle.write("--- stderr ---\n")
                handle.write(completed.stderr[-8000:])
        handle.write(f"exit={exit_code}\n")


def run_invocation(
    entry_id: str, header: str, command: list[str], timeout: int, environment: dict[str, str]
) -> int:
    output_path = OUTPUT / f"{entry_id}.txt"
    try:
        completed = subprocess.run(
            command, cwd=BACKEND, env=environment, capture_output=True, text=True,
            encoding="utf-8", errors="replace", timeout=timeout,
        )
        exit_code = completed.returncode
    except subprocess.TimeoutExpired:
        capture(output_path, header, None, 124)
        print(f"entry={entry_id} exit=124 timeout", flush=True)
        return 124
    capture(output_path, header, completed, exit_code)
    print(f"entry={entry_id} exit={exit_code}", flush=True)
    return exit_code


def run_group_entry(group: dict) -> int:
    environment = build_environment(group["run_id"], 5432)
    command = ["uv", "run", "--no-sync", "python", "-m", "pytest", *group["args"], "-q"]
    if not group.get("coverage", False):
        command.append("--no-cov")
    header = f"run_id={group['run_id']}\nargs={json.dumps(group['args'])}\n"
    return run_invocation(group["id"], header, command, GROUP_TIMEOUT_SECONDS, environment)


def run_file_entry(entry: dict) -> int:
    environment = build_environment(entry["run_id"], entry.get("port", 5432))
    command = [
        "uv", "run", "--no-sync", "python", "-m", "pytest", entry["file"], "-q", "--no-cov",
    ]
    header = (
        f"run_id={entry['run_id']}\nport={entry.get('port', 5432)}\n"
        f"pin_ambiguity={entry.get('pin_ambiguity', False)}\nfile={entry['file']}\n"
    )
    return run_invocation(
        Path(entry["file"]).stem + "_pf", header, command, FILE_TIMEOUT_SECONDS, environment
    )


def main() -> int:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    if PLAN.get("mode") == "per_file":
        entries = PLAN["files"]
        runner = run_file_entry
    else:
        entries = PLAN["groups"]
        runner = run_group_entry
    failures = 0
    for entry in entries:
        try:
            if runner(entry) != 0:
                failures += 1
        except subprocess.CalledProcessError as failure:
            print(f"entry={entry.get('id', entry.get('file'))} provisioning_failed rc={failure.returncode}", flush=True)
            failures += 1
    print(f"entries_total={len(entries)} entries_failed={failures}", flush=True)
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
'''


def parse_arguments(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="dev_integration_container.py",
        description=(
            "Run the grouped isolated-PostgreSQL test plan in one throwaway "
            "container; group outputs land in the evidence directory."
        ),
    )
    parser.add_argument("--plan", type=Path, required=True, help="groups JSON plan")
    parser.add_argument("--evidence-dir", type=Path, required=True, help="mounted output directory")
    parser.add_argument("--image-tag", default=DEFAULT_IMAGE_TAG)
    parser.add_argument(
        "--keep-cache", action="store_true",
        help="keep the uv download cache volume for follow-up runs",
    )
    return parser.parse_args(argv)


def run_docker(arguments: list[str], timeout_seconds: int) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["docker", *arguments], capture_output=True, text=True,
        encoding="utf-8", errors="replace", timeout=timeout_seconds,
    )


def main(argv: list[str] | None = None) -> int:
    arguments = parse_arguments(argv)
    arguments.evidence_dir.mkdir(parents=True, exist_ok=True)
    container_name = "dianzi-batch21-integration"
    run_docker(["rm", "-f", container_name], timeout_seconds=120)

    with tempfile.TemporaryDirectory(prefix="dianzi_batch21_int_") as scripts_name:
        scripts_dir = Path(scripts_name)
        (scripts_dir / "run_container.sh").write_text(
            CONTAINER_RUNNER, encoding="utf-8", newline="\n"
        )
        (scripts_dir / "run_groups.py").write_text(
            GROUPS_RUNNER_PYTHON, encoding="utf-8", newline="\n"
        )
        docker_arguments = [
            "run", "--rm", "--name", container_name,
            "--memory", CONTAINER_MEMORY, "--cpus", CONTAINER_CPUS,
            "-v", f"{REPO_ROOT.as_posix()}:/repo:ro",
            "-v", f"{scripts_dir / 'run_container.sh'}:/run_container.sh:ro",
            "-v", f"{scripts_dir / 'run_groups.py'}:/run_groups.py:ro",
            "-v", f"{arguments.plan.resolve().as_posix()}:/groups.json:ro",
            "-v", f"{arguments.evidence_dir.resolve().as_posix()}:/out",
            "-v", f"{CACHE_VOLUME}:/tmp/uv-cache",
            arguments.image_tag,
            "bash", "/run_container.sh",
        ]
        try:
            completed = run_docker(docker_arguments, timeout_seconds=RUN_TIMEOUT_SECONDS)
            exit_code = completed.returncode
        except subprocess.TimeoutExpired:
            exit_code = 124
            completed = None
        run_docker(["rm", "-f", container_name], timeout_seconds=120)
    if not arguments.keep_cache:
        run_docker(["volume", "rm", CACHE_VOLUME], timeout_seconds=120)

    summary_path = arguments.evidence_dir / "container_run_summary.txt"
    with summary_path.open("a", encoding="utf-8") as handle:
        handle.write(f"=== docker run ({datetime.now(UTC).isoformat()}) ===\n")
        if completed is not None:
            if completed.stdout:
                handle.write(completed.stdout)
            if completed.stderr:
                handle.write("--- stderr ---\n")
                handle.write(completed.stderr[-4000:])
        handle.write(f"exit={exit_code}\n")
    return 0 if exit_code == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
