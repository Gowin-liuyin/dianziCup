import fs from "node:fs/promises";
import process from "node:process";
import { expect, test } from "@playwright/test";

import { parseQuestionAnswer } from "../src/api/question-contracts";

test("R05 repaired real source question reaches the browser and fixed revision evidence", async ({ page }, testInfo) => {
  const username = process.env.DIANZI_E2E_USERNAME;
  const password = process.env.DIANZI_E2E_PASSWORD;
  const eventId = process.env.DIANZI_LIVE_EVENT_ID;
  if (!username || !password || !eventId) throw new Error("owned live test configuration unavailable");
  const login = await page.request.post("/v1/auth/login", { data: { username: `${username}-r04-admin`, password }, headers: { Origin: "http://127.0.0.1:25300" } });
  expect(login.status()).toBe(200);
  await page.setViewportSize({ width: 1366, height: 900 });
  await page.goto(`/#events/${eventId}`);
  await page.getByRole("link", { name: "基于此事件提问 →", exact: true }).click();
  await expect(page.getByLabel("事件标识", { exact: true })).toHaveValue(eventId);
  await page.getByLabel("你的问题", { exact: true }).fill("请概括这条公告明确记载的一项安全风险或受影响事实，必须保留原文条件。");
  const responsePromise = page.waitForResponse((response) => response.url().endsWith("/v1/questions") && response.request().method() === "POST", { timeout: 95_000 });
  const started = performance.now();
  await page.getByRole("button", { name: "提交问题", exact: true }).click();
  const response = await responsePromise;
  const body: unknown = await response.json();
  const elapsed = performance.now() - started;
  await fs.writeFile(testInfo.outputPath("actual_question.json"), JSON.stringify({ observed_at_utc: new Date().toISOString(), code_sha: "dc014c960f19605c20e0d8e98a93e7c217f94cc6", status: response.status(), complete_browser_elapsed_milliseconds: elapsed, body }, null, 2));
  expect(response.status()).toBe(200);
  const answer = parseQuestionAnswer(body);
  expect(answer.data_mode).toBe("live");
  expect(answer.citations.length).toBeGreaterThan(0);
  const result = page.getByRole("article", { name: "完整证据回答", exact: true });
  await expect(result).toBeVisible();
  await expect(result.getByText("真实 / Live", { exact: true })).toBeVisible();
  await expect(result.locator(".question-answer-text")).toHaveText(answer.answer_text);
  await result.getByRole("link", { name: "依据 [1]", exact: true }).first().click();
  await expect(page.locator(`#citation-${answer.citations[0]?.evidence_id}`)).toBeFocused();
  await expect(page.getByTestId("ambient-motion")).toHaveCSS("animation-name", "topology-drift");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("real-question-desktop-1366.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await expect(page.getByTestId("ambient-motion")).toHaveCSS("animation-name", "none");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("real-question-mobile-390.png"), fullPage: true });
  const citation = answer.citations[0];
  if (citation === undefined) throw new Error("completed live answer has no citation");
  await page.getByRole("link", { name: "检视固定修订证据 [1] →", exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`/evidence/${citation.evidence_id}/revision/${citation.revision_id}$`));
  await expect(page.locator(".evidence-body blockquote")).toContainText(citation.quote);
  await page.reload();
  await expect(page.locator(".evidence-body blockquote")).toContainText(citation.quote);
  await page.goto("/#questions");
  await page.getByLabel("回答标识", { exact: true }).fill(answer.answer_id);
  await page.getByRole("button", { name: "查询 / 刷新回答", exact: true }).click();
  await expect(page.locator(".question-answer-text")).toHaveText(answer.answer_text);
  await expect(page.getByText("此回答未返回事件标识，无法确认内部事件链接；仍可核对引文、修订标识和来源原文。", { exact: true })).toBeVisible();
  await page.goto("/#session");
  await page.getByRole("button", { name: "退出登录", exact: true }).click();
  await expect(page.getByRole("button", { name: "登录工作台", exact: true })).toBeVisible();
});
